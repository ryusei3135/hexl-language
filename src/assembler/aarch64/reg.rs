//! レジスタの定義表
//!
//! # レジスタを追加するには
//!
//! 下の `define_regs!` に **1行足すだけ** です。他のファイルは変更不要です。
//!
//! ```text
//! バリアント名 => ("アセンブリ上の名前", レジスタ番号(0-31), ビット幅),
//! ```
//!
//! - `enum Reg` / `Reg::id()` / `Reg::bits()` / `Reg::from_name()` は
//!   すべてこの表から自動生成される。
//! - 番号 31 は命令によって `%sp` (スタックポインタ) にも `%xzr` / `%wzr`
//!   (ゼロレジスタ) にもなる。区別は `is_sp()` / `is_zr()` で行う。
//! - `%fp` (= `%x29`) と `%lr` (= `%x30`) は `from_name` の別名として扱う。
//! - SIMD / 浮動小数点レジスタ (`%v0` / `%d0` / `%s0` ...) は未対応。
//!   追加するときは `bits` に 8/16/32/64/128 を使い、`is_vector()` を足す。

macro_rules! define_regs {
    ( $( $variant:ident => ($name:literal, $id:literal, $bits:literal) ),* $(,)? ) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub enum Reg {
            $( $variant ),*
        }

        impl Reg {
            /// 命令に埋め込むレジスタ番号 (0-31)
            pub fn id(self) -> u32 {
                match self {
                    $( Reg::$variant => $id ),*
                }
            }

            /// レジスタのビット幅 (32 / 64)
            pub fn bits(self) -> u32 {
                match self {
                    $( Reg::$variant => $bits ),*
                }
            }

            /// アセンブリ上の名前 (`%x0` など) から `Reg` を引く
            pub fn from_name(name: &str) -> Option<Reg> {
                match name {
                    "%fp" => return Some(Reg::X29),
                    "%lr" => return Some(Reg::X30),
                    _ => {}
                }

                match name {
                    $( $name => Some(Reg::$variant), )*
                    _ => None,
                }
            }

            /// 64bit か (`sf` ビットの値)
            pub fn is_64(self) -> bool {
                self.bits() == 64
            }

            /// `%sp` / `%wsp` か
            pub fn is_sp(self) -> bool {
                matches!(self, Reg::Sp | Reg::Wsp)
            }

            /// `%xzr` / `%wzr` か
            pub fn is_zr(self) -> bool {
                matches!(self, Reg::Xzr | Reg::Wzr)
            }
        }
    };
}

