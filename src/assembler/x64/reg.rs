//! レジスタの定義表
//!
//! # レジスタを追加するには
//!
//! 下の `define_regs!` に **1行足すだけ** です。(ビット幅は 8〜512)他のファイルは変更不要です。
//!
//! ```text
//! バリアント名 => ("アセンブリ上の名前", レジスタ番号(0-15), ビット幅 8/16/32/64/128/256/512),
//! ```
//!
//! - `enum Reg` / `Reg::id()` / `Reg::bits()` / `Reg::from_name()` は
//!   すべてこの表から自動生成される。
//! - アセンブリ文字列 -> `Reg` の変換 (`convert.rs`) は `Reg::from_name` を使う。

macro_rules! define_regs {
    ( $( $variant:ident => ($name:literal, $id:literal, $bits:literal) ),* $(,)? ) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub enum Reg {
            $( $variant ),*
        }

        impl Reg {
            /// ModRM / REX に埋め込むレジスタ番号 (0-15)
            pub fn id(self) -> u8 {
                match self {
                    $( Reg::$variant => $id ),*
                }
            }

            /// レジスタのビット幅 (8 / 16 / 32 / 64 / 128 / 256 / 512)
            pub fn bits(self) -> u16 {
                match self {
                    $( Reg::$variant => $bits ),*
                }
            }

            /// アセンブリ上の名前 (`%rax` など) から `Reg` を引く
            pub fn from_name(name: &str) -> Option<Reg> {
                match name {
                    $( $name => Some(Reg::$variant), )*
                    _ => None,
                }
            }

            /// REX プレフィックスが必要な拡張レジスタ (`%r8`-`%r15` 系、`%xmm8`-`%xmm15` 系) か
            pub fn is_extended(self) -> bool {
                self.id() >= 8
            }

            /// ベクトルレジスタ (`%xmm` / `%ymm` / `%zmm`) か
            pub fn is_vector(self) -> bool {
                self.bits() >= 128
            }
        }
    };
}

